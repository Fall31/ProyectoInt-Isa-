-- Ejecutar en Supabase SQL editor

BEGIN;

-- NOTA: Este script NO cambia tipos de columnas usadas por RLS directamente.
-- Aplica estrategia segura con columnas "gemelas" para evitar romper políticas.

-- 1) Asegurar tabla existe (no crea nueva estructura incompatible)
CREATE TABLE IF NOT EXISTS public.cliente (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

-- 2) Asegurar columnas base (sin tocar tipos existentes)
ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS user_id text; -- si ya es uuid, no se modifica aquí
ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS correo_cliente text;
-- Hash opcional del correo (nullable) para privacidad/deduplicación
ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS correo_cliente_hash text;
ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS ci_cliente text;
