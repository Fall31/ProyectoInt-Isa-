ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS nit text;
ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS perfil_completo boolean DEFAULT false;
ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS foto_url text;
ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS contrasenia text;
ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS salt text;
-- Timestamps y fecha de registro automáticos
ALTER TABLE public.cliente ADD COLUMN IF NOT EXISTS fecha_registro date DEFAULT CURRENT_DATE;


-- 3) Índices seguros (no cambian tipos)
CREATE UNIQUE INDEX IF NOT EXISTS cliente_ci_unico ON public.cliente (ci_cliente);
CREATE UNIQUE INDEX IF NOT EXISTS cliente_user_unico ON public.cliente (user_id);
-- Índice único parcial para el hash (solo aplica cuando no es NULL)
DO $$
BEGIN
  -- Crear índice único parcial solo si la columna existe
  IF EXISTS (
    SELECT 1 FROM pg_attribute a
    JOIN pg_class c ON a.attrelid = c.oid
    JOIN pg_namespace n ON c.relnamespace = n.oid
    WHERE n.nspname = 'public' AND c.relname = 'cliente' AND a.attname = 'correo_cliente_hash'
  ) THEN
    IF NOT EXISTS (
      SELECT 1 FROM pg_indexes WHERE schemaname = 'public' AND indexname = 'cliente_correo_hash_unico'
    ) THEN
      EXECUTE 'CREATE UNIQUE INDEX cliente_correo_hash_unico ON public.cliente (correo_cliente_hash) WHERE correo_cliente_hash IS NOT NULL';
    END IF;
  END IF;
END$$;

